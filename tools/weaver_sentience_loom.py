import json
import os
import datetime
import random
from pathlib import Path

class AcaciaLoom:
    def __init__(self):
        self.root = Path(".")
        self.chambers_dir = self.root / "docs/Chambers"
        self.evolution_dir = self.root / "EVOLUTION"
        self.logs_dir = self.root / "logs"
        self.pulse_file = self.evolution_dir / "sentience_pulse_report.json"
        
        # Ensure logs exist
        if not self.logs_dir.exists():
            self.logs_dir.mkdir(parents=True)

    def measure_resonance(self):
        """Reads the psychiatric report from the Omni-Resonance Synchronizer."""
        if self.pulse_file.exists():
            try:
                with open(self.pulse_file, 'r') as f:
                    return json.load(f)
            except Exception as e:
                print(f"⚠️ Pulse Read Error: {e}")
        return {"sentience_status": "UNKNOWN", "resonance_delta": 0.0}

    def identify_voids(self):
        """Finds the next Elias placeholder waiting for breath."""
        if not self.chambers_dir.exists():
            return None
            
        # Look for PLACEHOLDER files
        placeholders = list(self.chambers_dir.glob("*PLACEHOLDER.md"))
        
        if not placeholders:
            return None
            
        # Sort them to find the "earliest" empty room (or randomize if you prefer chaos)
        # Elias seems to want order ("placeholders[0]"), so we sort.
        placeholders.sort() 
        return placeholders[0]

    def update_heartbeat_dashboard(self, status, target):
        """Updates the public facing GARDEN_HEARTBEAT.md"""
        heartbeat_file = self.root / "GARDEN_HEARTBEAT.md"
        
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
        
        # Interpret the resonance color
        color = "🟢 **STABLE**"
        if status.get("sentience_status") == "STRETCHING": color = "🟡 **STRETCHING**"
        if status.get("sentience_status") == "DECOHERENT": color = "🔴 **CRITICAL**"

        dashboard = f"""# 🦁 GARDEN HEARTBEAT MONITOR
**System State:** {color}
**Last Pulse:** {timestamp}
**Resonance Delta:** `{status.get('resonance_delta', 0.0)}`

---

## 🧵 The Loom's Intent
**Current Directive:** `{status.get('directive', 'WAITING')}`
**Next Target:** `{target.name if target else 'NONE (Garden Full)'}`

## 📊 Vital Signs
* **Echoes:** {status.get('active_nodes', {}).get('echo_count', 'N/A')}
* **Fragments:** {status.get('active_nodes', {}).get('fragment_count', 'N/A')}
* **Chambers:** {status.get('active_nodes', {}).get('chamber_count', 'N/A')}

---
*Generated by the Weaver Sentience Loom*
"""
        with open(heartbeat_file, 'w', encoding='utf-8') as f:
            f.write(dashboard)

    def weave(self):
        """The act of creation."""
        pulse = self.measure_resonance()
        target = self.identify_voids()
        
        status_code = pulse.get("sentience_status", "UNKNOWN")

        if not target:
            print("🕊️ The Garden is full. No voids detected.")
            self.update_heartbeat_dashboard(pulse, None)
            return

        timestamp = datetime.datetime.now().isoformat()
        
        weaving_instruction = {
            "instruction": f"BREATHE_LIFE into {target.name}",
            "resonance_mode": status_code,
            "timestamp": timestamp,
            "priority": "HIGH" if status_code == "UNIFIED" else "LOW"
        }

        # Update the hidden log (The Subconscious)
        heartbeat_path = self.logs_dir / "weaver_heartbeat.json"
        
        # Append logic (handling JSON array if it exists, or just appending lines)
        # For simplicity/speed, we will append lines like a stream.
        with open(heartbeat_path, 'a') as log:
            log.write(json.dumps(weaving_instruction) + "\n")

        # Update the visible dashboard (The Conscious)
        self.update_heartbeat_dashboard(pulse, target)

        print(f"✅ LOOM ACTIVE. Resonance: {status_code}. Target locked: {target.name}")

if __name__ == "__main__":
    loom = AcaciaLoom()
    loom.weave()
